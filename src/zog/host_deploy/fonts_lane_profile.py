PROFILE = "host-deploy-first-fonts-retained-lane-v3"
FACTS_SCHEMA = "host-deploy-verified-first-fonts-installed-v2"
LANE = "gateway-first-fonts-runtime"
PROJECT_ROOT = str(lanes.DEFAULT_ROOT / LANE)  # fresh-profile root, NOT historical root
RETAINED_PROJECT_ROOT = "/home/certbot-build-owner/gateway-first-fonts-runtime"
RETAINED_SPECIFICATION_SHA256 = "sha256:c7ab129937330fab5f74ae37b16a0b3e8de35cf87cef1fdda33d18bbcf1779f2"
COMPILER_INSTANCE = "i-00ad300038a599044"
FACTS_FILE = "first-fonts-verified-facts-v2.json"
INTENT_FILE = "first-fonts-activation-intent-v1.json"
FACTS_MAX_AGE_SECONDS = 3600
COMPANION_REVISION = "a866c9c4b0dd385045f00ce2de7d809f5b67c104"


def _canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode("ascii")


def _digest(value):
    return "sha256:" + hashlib.sha256(_canonical(value)).hexdigest()


def _read_regular(path):
    path = Path(path)
    if path.is_symlink() or not path.is_file():
        raise RuntimeError("expected regular, nonsymlinked workspace evidence: " + str(path))
    return json.loads(path.read_text())


def _owner(directory):
    workspace, host = configuration(directory)
    if (not isinstance(host, dict)
            or host.get("instance_id") != COMPILER_INSTANCE
            or not re.fullmatch(r"[0-9]{12}", host.get("account_id", ""))
            or not isinstance(host.get("workspace_id"), str)
            or host.get("region") != workspace["region"]
            or host["workspace_id"] != workspace["workspace_id"]):
        raise RuntimeError("first Fonts requires the original workspace-owned compiler Host")
    return workspace, host


def _binding(workspace, host):
    return {key: value for key, value in (
        ("workspace_id", workspace["workspace_id"]),
        ("account_id", host["account_id"]),
        ("region", host["region"]),
        ("instance_id", host["instance_id"]),
    )}


def profile():
    """Source pins and reviewed retained-lane identity, not a new lane spec."""
    if (fonts.SOURCE != lanes.FIRST_FONTS_PRODUCER_REVISION
            or lanes.expected_build_record_revision(fonts.SOURCE) != COMPANION_REVISION):
        raise RuntimeError("first Fonts producer/companion source review differs")
    return {
        "schema": PROFILE,
        "lane": LANE,
        "source_repository": fonts.REPOSITORY,
        "source_revision": fonts.SOURCE,
        "monthly_pin_repository_path": fonts.PIN_PATH,
        "monthly_pin_identity": "sha256:" + fonts.PIN_SHA256,
        "build_record_revision": COMPANION_REVISION,
        "retained_specification_sha256": RETAINED_SPECIFICATION_SHA256,
        "retained_project_root": RETAINED_PROJECT_ROOT,
        "compiler_instance_id": COMPILER_INSTANCE,
        "controller_producer": "zog.host_deploy.image_build_lanes._controller",
    }


def _retained(root):
    """Read every retained record; conflicting or malformed history holds."""
    directory = root / "image-build-lanes"
    if directory.is_symlink() or (directory.exists() and not directory.is_dir()):
        raise RuntimeError("unsafe retained lane directory")
    records = []
    for path in sorted(directory.glob("*.json")):
        record = _read_regular(path)
        if (not isinstance(record, dict)
                or record.get("lane") != path.stem
                or record.get("schema") not in lanes._RECORD_SCHEMAS
                or record.get("state") not in {"prepared", "active", "retired"}):
            raise RuntimeError("invalid retained image-build lane history")
        spec = lanes.validate(record.get("specification"))
        if spec["lane"] != path.stem or spec["schema"] != record["schema"]:
            raise RuntimeError("inconsistent retained image-build lane identity")
        records.append(record)
    return records


def _approved(root, *, records=None):
    """Compare the *actual retained* specification, never produce a substitute."""
    reviewed = profile()
    records = _retained(root) if records is None else records
    selected = [record for record in records if record["lane"] == LANE]
    if len(selected) != 1:
        raise RuntimeError("approved first Fonts retained record is missing or ambiguous")
    record = selected[0]
    spec = lanes.validate(record["specification"])
    digest = lanes.specification_sha256(spec)
    if (record["schema"] != lanes.SCHEMA
            or spec["schema"] != lanes.SCHEMA
            or spec["mode"] != "managed"
            or spec["project_root"] != RETAINED_PROJECT_ROOT
            or digest != RETAINED_SPECIFICATION_SHA256
            or spec["source_repository"] != reviewed["source_repository"]
            or spec["source_revision"] != reviewed["source_revision"]
            or spec["monthly_pin_repository_path"] != reviewed["monthly_pin_repository_path"]
            or spec["monthly_pin_identity"] != reviewed["monthly_pin_identity"]
            or record["state"] not in {"prepared", "active"}
            or "fonts_lane_profile" in record):
        raise RuntimeError("retained first Fonts digest/source/controller/root differs from approval")
    # Snapshot the whole existing specification, including controller and
    # provenance Project IDs. No replacement UID, root, or policy is allowed.
    others = [item for item in records if item["lane"] != LANE]
    if fonts_lane_review.review(others, spec)["status"] != "DISTINCT_LANE_PROPOSAL_NOT_PREPARED":
        raise RuntimeError("another retained lane conflicts with approved first Fonts identity")
    for other in others:
        previous = other["specification"]
        if (previous["project_root"] == spec["project_root"]
                or previous["provenance_project_id"] == spec["provenance_project_id"]):
            raise RuntimeError("retained first Fonts Project identity is not unique")
    return record, spec, digest


def verify(directory, *, now=None):
    """Inspect the old source/Host/digest as evidence; never select a worker.

    The old UID/GID fields are not an authorized way to execute compilation.
    Runtime access must be verified by the actual effective compiler process
    after a source-reviewed inherited-identity migration.
    """
    with locked(directory) as root:
        workspace, host = _owner(root)
        record, spec, digest = _approved(root)
        return {"schema": "host-deploy-first-fonts-historical-inspection-v1",
                "historical_specification_sha256": digest,
                "project_root": spec["project_root"], "state": record["state"],
                "workspace": str(root), "binding": _binding(workspace, host),
                "execution_authorized": False,
                "migration_required": True}


def prepare(directory, *, now=None):
    """Read-only compatibility: never recreate or migrate a retained Fonts lane.

    The first Fonts target already has an approved prepared specification; if
    it cannot be recovered from the owner workspace, fail instead of inventing
    source-owned values. A future fresh lane needs a separate reviewed producer.
    """
    with locked(directory) as root:
        workspace, host = _owner(root)
        record, spec, _ = _approved(root)
        return record  # Historical evidence only; not an authorization.


def validate_activation(root, record, spec, workspace, host, *, expected_specification_sha256):
    """Validate the retained exact lane under the owning workspace lock."""
    if host.get("instance_id") != COMPILER_INSTANCE:
        raise RuntimeError("original Fonts deployment differs from approved Host")
    # Retained v4 UID/GID selectors are historical evidence only. Migration
    # must produce a different spec/digest before the webhook can execute.
    if spec["schema"] == lanes.SCHEMA and {"execution_user_id", "execution_group_id"} <= set(spec["controller"]):
        raise RuntimeError("legacy first Fonts worker UID/GID cannot authorize execution; use explicit inherited-identity migration")
    selected, existing, digest = _approved(root)
    if (selected != record or existing != spec
            or expected_specification_sha256 != digest):
        raise RuntimeError("original Fonts activation digest/Host/source differs")
    # For an already-active matching lane, each repeat activation performs a
    # fresh read-only installed probe. Do not require a separate recent local
    # verification snapshot merely to observe an already active installation.
    # Prepared lanes still require explicit, recent source-owned verification.
    if selected["state"] == "prepared":
        raise RuntimeError("inherited-execution migration required before first Fonts activation")
    return selected


def activation_intent(root, workspace, host, spec):
    """Create a durable, non-replayable local intent before *any* remote write."""
    digest = lanes.specification_sha256(spec)
    expected = {"schema": "host-deploy-first-fonts-activation-intent-v1",
                "specification_sha256": digest, "binding": _binding(workspace, host)}
    path = root / INTENT_FILE
    if path.exists() or path.is_symlink():
        current = _read_regular(path)
        if current != expected:
            raise RuntimeError("existing first Fonts activation intent conflicts")
    else:
        save(path, expected)
    return expected
