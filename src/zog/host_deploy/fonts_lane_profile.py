"""First Fonts: retain the approved lane and inspect its installed controller.

The existing workspace record is the authority for lane-owned identity and
policy. root-control and Linux own the installed socket/account facts; the
controller.json bytes are generated by image_build_lanes, never hand-authored.
No missing historical lane is recreated or silently migrated to a new root.
"""
